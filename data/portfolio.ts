/** Corpus for the in-page trigram model: every sentence on the site. */
export function corpus(): string {
  const chunks: string[] = [
    site.description,
    hero.lines.join(" "),
    hero.descriptor,
    ...hero.cards.map((c) => c.line),
    ...about.paragraphs,
    statement.lines.join(" "),
    ...statement.notes.map((n) => n.text),
    statement.body,
    statement.aside,
    ...origin.chapters.map((c) => c.parts.map((p) => (typeof p === "string" ? p : p.accent)).join("")),
    origin.turn,
    method.headline.join(" "),
    method.body,
    method.depth,
    method.confidence,
    ...projects.flatMap((p) => [...p.body, ...p.long]),
    ...toolkit.right.body,
    ...pitch.body,
    pitch.diaryIntro,
    pitch.proud,
    ...close.next,
    close.body,
  ];
  return chunks.join(" ");
}
